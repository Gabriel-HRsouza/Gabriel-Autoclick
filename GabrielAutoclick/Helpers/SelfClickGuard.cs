using System;
using System.Runtime.InteropServices;

namespace GabrielAutoclick.Helpers
{
    /// <summary>
    /// Second line of defence against the app clicking its own controls.
    ///
    /// Every synthetic mouse event sent by the automations carries <see cref="Signature"/> in
    /// dwExtraInfo. Windows hands that value back through GetMessageExtraInfo() while the
    /// receiving window processes the message, so the app's own control buttons can tell an
    /// automated click (ignored) from a real one (accepted) exactly, with no timing guesswork.
    /// </summary>
    public static class SelfClickGuard
    {
        /// <summary>"GAC1" — marks input generated by Gabriel Autoclick.</summary>
        public static readonly IntPtr Signature = (IntPtr)0x47414331;

        [DllImport("user32.dll")]
        private static extern IntPtr GetMessageExtraInfo();

        /// <summary>
        /// Call from a click handler on the UI thread: true when the mouse message being
        /// processed was produced by Gabriel Autoclick itself.
        /// </summary>
        public static bool IsCurrentInputSynthetic()
        {
            try
            {
                return GetMessageExtraInfo() == Signature;
            }
            catch
            {
                return false;
            }
        }
    }
}
